import { type ReactNode } from 'react';
import { AlertCircle, Inbox, RefreshCw, FlaskConical } from 'lucide-react';

export function EmptyState({
  title = 'No records found',
  description = 'There is currently no data matching your criteria.',
  icon,
  action,
}: {
  title?: string;
  description?: string;
  icon?: ReactNode;
  action?: ReactNode;
}) {
  return (
    <div className="es-empty" role="status">
      <div className="es-empty-icon">
        {icon || <Inbox size={32} />}
      </div>
      <h4 className="es-empty-title">{title}</h4>
      <p className="es-empty-description">{description}</p>
      {action && <div style={{ marginTop: 'var(--space-3)' }}>{action}</div>}
    </div>
  );
}

export function ErrorState({
  title = 'Failed to load telemetry',
  description = 'A network or aggregation error occurred while retrieving this dataset.',
  onRetry,
}: {
  title?: string;
  description?: string;
  onRetry?: () => void;
}) {
  return (
    <div className="es-empty" role="alert" style={{ borderColor: 'var(--color-danger-200)' }}>
      <div className="es-empty-icon" style={{ color: 'var(--color-danger-500)' }}>
        <AlertCircle size={32} />
      </div>
      <h4 className="es-empty-title" style={{ color: 'var(--color-danger-700)' }}>{title}</h4>
      <p className="es-empty-description">{description}</p>
      {onRetry && (
        <button
          type="button"
          onClick={onRetry}
          style={{
            marginTop: 'var(--space-3)',
            display: 'inline-flex',
            alignItems: 'center',
            gap: 'var(--space-2)',
            padding: 'var(--space-2) var(--space-4)',
            background: 'var(--surface-card)',
            border: '1px solid var(--color-neutral-300)',
            borderRadius: 'var(--radius-md)',
            fontSize: 'var(--font-size-sm)',
            fontWeight: 'var(--font-weight-medium)',
            cursor: 'pointer',
          }}
        >
          <RefreshCw size={14} /> Retry
        </button>
      )}
    </div>
  );
}

